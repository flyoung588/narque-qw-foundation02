"""Human-window AI chooses requests; runner executes no hidden model calls or presets.

Round2 requires a hash-bound decision written AFTER actual round1 observations.
This gate proves provenance, not intelligence: the preserved AI reasoning is also required.
"""
import copy,json,pathlib,sys
from router import run,save,digest,compare,physical_key
def authorize_next(decision,prior):
 if prior.get('status')!='CALCULATED':raise ValueError('No CALCULATED feedback; retain unavailable/failure, do not fabricate')
 if decision.get('based_on_observation_sha256')!=digest(prior):raise ValueError('Feedback hash mismatch')
 if not decision.get('analysis_after_observation') or not decision.get('changed_because'):raise ValueError('Missing actual post-observation reasoning')
 if decision.get('action') not in ('compute','stop'):raise ValueError('Unknown decision action')
 if decision['action']=='compute' and physical_key(decision['worldspec'])==physical_key(prior['spec']):raise ValueError('No actual condition change')
 return decision
def execute(request,outdir):
 out=pathlib.Path(outdir);out.mkdir(parents=True,exist_ok=True);save(out/'request.json',request)
 if request['round']==2:
  prior=request['prior_observation'];authorize_next(request['decision'],prior)
  if request['decision']['action']=='stop':save(out/'stop.json',request['decision']);return
  spec=request['decision']['worldspec']
 elif request['round']==1:spec=request['worldspec']
 else:raise ValueError('Only two bounded rounds supported')
 observations=[]
 for engine in ['pyscf','psi4']:
  s=copy.deepcopy(spec);s['physics']['engine']=engine;observations.append(run(s,out/engine))
 save(out/'cross_engine.json',compare(*observations))
 save(out/'next_context.json',{'observations':observations,'question':'Read actual data and choose next experiment or justified stop. No successor geometry generated by this runner.','observation_sha256':digest(observations[0]),'classification':'WAITING_FOR_ACTUAL_AI_FEEDBACK_NOT_PRESET_ADAPTIVITY'})
 if request['round']==2:
  prior=request['prior_observation'];now=observations[0]
  a=physical_key(prior['spec']);b=physical_key(now['spec']);a['matter'].pop('atoms');b['matter'].pop('atoms')
  species_same=[x['element'] for x in prior['spec']['matter']['atoms']]==[x['element'] for x in now['spec']['matter']['atoms']]
  if a==b and species_same and prior['status']==now['status']=='CALCULATED':
   save(out/'feedback_comparison.json',{'energy_change_Eh':now['observation']['energy_Eh']-prior['observation']['energy_Eh'],'prediction':request['decision']['prediction'],'reasoning':request['decision']['analysis_after_observation'],'physical_accuracy':'NOT_CERTIFIED','mechanism_novelty':'NOT_TESTED'})
if __name__=='__main__':execute(json.loads(pathlib.Path(sys.argv[1]).read_text()),sys.argv[2])
